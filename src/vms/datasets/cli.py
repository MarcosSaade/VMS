"""`python -m vms.datasets`: fetch clips, write the manifest, pin checksums.

    fetch --subset full|mini [--accept-license virat]   (make data / make data-mini)
    pin <clip_id>                                        print the checksum for a new source

`fetch` is idempotent: a clip whose `clip.json` matches the spec hash is skipped, cached raw
files are reused after re-verification, and nothing is half-written on failure. Clips whose
license requires acceptance are skipped (with a message) unless accepted explicitly.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

import yaml

from vms.common.logs import configure_logging, get_logger
from vms.datasets.clips import (
    ClipManifest,
    fetch_clip,
    is_current,
    members_digest,
    read_manifest,
    read_zip_members,
)
from vms.datasets.http import RetryPolicy, Transport, UrllibTransport
from vms.datasets.spec import DataSpec, ZipSequenceSource, load_spec

log = get_logger(__name__)

DEFAULT_SPEC = Path("configs/data/sources.yaml")
DEFAULT_MANIFEST = Path("configs/data/manifest.yaml")
DEFAULT_DATA_DIR = Path("data")


def fetch(
    spec: DataSpec,
    subset: str,
    data_dir: Path,
    transport: Transport,
    retry: RetryPolicy,
    accepted: frozenset[str] = frozenset(),
) -> tuple[list[ClipManifest], list[str]]:
    """Fetch every clip in `subset`. Returns (manifests of present clips, skipped clip ids)."""
    present: list[ClipManifest] = []
    skipped: list[str] = []
    for clip in spec.subset(subset):
        license_ = spec.licenses[clip.license]
        if license_.requires_acceptance and clip.license not in accepted:
            log.warning(
                "skipping clip: license must be accepted first",
                extra={
                    "clip": clip.id,
                    "license": clip.license,
                    "terms": str(license_.url),
                    "how": f"read the terms, then pass --accept-license {clip.license}",
                },
            )
            skipped.append(clip.id)
            continue
        if is_current(data_dir, clip, spec.processing):
            manifest = read_manifest(data_dir, clip.id)
            assert manifest is not None
            log.info("clip up to date", extra={"clip": clip.id})
        else:
            log.info("fetching clip", extra={"clip": clip.id, "source": str(clip.source.url)})
            manifest = fetch_clip(data_dir, clip, spec.processing, transport, retry)
            log.info(
                "clip ready",
                extra={
                    "clip": clip.id,
                    "frames": manifest.frames,
                    "fps": manifest.fps,
                    "size": f"{manifest.width}x{manifest.height}",
                },
            )
        present.append(manifest)
    return present, skipped


def write_manifest(
    path: Path,
    spec_version: int,
    clips: Sequence[ClipManifest],
    known: set[str] | None = None,
) -> None:
    """The committed record of what `make data` produces (measured values and content hashes).

    Clips are merged by id with any already listed, so `make data-mini` after `make data` does
    not drop entries; entries whose id is not in `known` (clips removed from the spec) are
    dropped. Clips that need license acceptance appear only if fetched locally.
    """
    existing: dict[str, dict[str, object]] = {}
    if path.is_file():
        loaded = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        existing = {c["id"]: c for c in loaded.get("clips", [])}
    if known is not None:
        existing = {k: v for k, v in existing.items() if k in known}
    for clip in clips:
        existing[clip.id] = clip.model_dump(mode="json")
    body = {
        "spec_version": spec_version,
        "clips": [existing[k] for k in sorted(existing)],
    }
    header = (
        "# Generated by `python -m vms.datasets fetch` (make data). Do not edit by hand.\n"
        "# Measured properties and content hashes of the normalized clips in data/clips/.\n"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + yaml.safe_dump(body, sort_keys=False, width=100), encoding="utf-8")


def compare_with_manifest(path: Path, clips: Sequence[ClipManifest]) -> list[str]:
    """Clips whose content hash differs from the committed manifest (same spec hash)."""
    if not path.is_file():
        return []
    committed = {
        c["id"]: c
        for c in (yaml.safe_load(path.read_text(encoding="utf-8")) or {}).get("clips", [])
    }
    drifted = []
    for clip in clips:
        old = committed.get(clip.id)
        if (
            old
            and old["spec_hash"] == clip.spec_hash
            and old["content_sha256"] != clip.content_sha256
        ):
            drifted.append(clip.id)
    return drifted


def pin(spec: DataSpec, clip_id: str, transport: Transport, retry: RetryPolicy, tmp: Path) -> str:
    """Compute the checksum to put in the spec for a zip-sequence clip (maintainers only:
    run it once when adding a clip, after checking the frames by eye)."""
    clip = spec.clip(clip_id)
    if not isinstance(clip.source, ZipSequenceSource):
        raise SystemExit("pin only applies to zip_sequence sources; video files publish checksums")
    return members_digest(read_zip_members(clip.source, transport, retry, tmp))


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m vms.datasets", description=__doc__)
    parser.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    parser.add_argument("--data-dir", type=Path, default=DEFAULT_DATA_DIR)
    parser.add_argument("--log-level", default="INFO")
    commands = parser.add_subparsers(dest="command", required=True)

    fetch_cmd = commands.add_parser("fetch", help="download, verify and normalize clips")
    fetch_cmd.add_argument("--subset", default="full")
    fetch_cmd.add_argument("--accept-license", action="append", default=[], metavar="ID")
    fetch_cmd.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    fetch_cmd.add_argument(
        "--strict",
        action="store_true",
        help="fail if a clip's content hash differs from the committed manifest",
    )

    pin_cmd = commands.add_parser("pin", help="print the checksum of a zip-sequence clip")
    pin_cmd.add_argument("clip_id")

    args = parser.parse_args(argv)
    configure_logging("datasets", args.log_level)
    spec = load_spec(args.spec)
    transport, retry = UrllibTransport(), RetryPolicy()
    args.data_dir.mkdir(parents=True, exist_ok=True)

    if args.command == "pin":
        print(pin(spec, args.clip_id, transport, retry, args.data_dir))  # noqa: T201 - CLI output
        return 0

    unknown = set(args.accept_license) - set(spec.licenses)
    if unknown:
        parser.error(f"unknown license ids: {sorted(unknown)}")
    clips, skipped = fetch(
        spec, args.subset, args.data_dir, transport, retry, frozenset(args.accept_license)
    )
    drifted = compare_with_manifest(args.manifest, clips)
    if drifted:
        log.warning(
            "content hash differs from the committed manifest (different OpenCV/libjpeg build?)",
            extra={"clips": drifted},
        )
        if args.strict:
            return 1
    write_manifest(args.manifest, spec.version, clips, known={c.id for c in spec.clips})
    log.info(
        "data ready",
        extra={
            "subset": args.subset,
            "clips": len(clips),
            "skipped": skipped,
            "data_dir": str(args.data_dir),
        },
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
