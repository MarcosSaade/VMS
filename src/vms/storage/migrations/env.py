"""Alembic environment: runs migrations online against POSTGRES_* (or an explicit URL).

Migrations are hand-written SQL (`op.execute`), not autogenerated from ORM models: the services
use psycopg directly and there are no models to diff against. Tests pass a URL with
`config.set_main_option("sqlalchemy.url", ...)` to target a throwaway database.
"""

from __future__ import annotations

from alembic import context
from sqlalchemy import create_engine, pool

from vms.storage.config import PostgresSettings

config = context.config
url = config.get_main_option("sqlalchemy.url") or PostgresSettings().sqlalchemy_url()

engine = create_engine(url, poolclass=pool.NullPool)
with engine.connect() as connection:
    context.configure(connection=connection, transactional_ddl=True)
    with context.begin_transaction():
        context.run_migrations()
